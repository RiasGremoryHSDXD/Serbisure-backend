"""Generate identical offline chat checks for the independently built web/mobile repos."""
import json
import sys
from pathlib import Path

backend = Path(__file__).resolve().parents[1]
workspace = backend.parents[1]
rules = json.loads((backend / 'chat/offensive_terms.json').read_text(encoding='utf-8'))
source = '// Generated by backend scripts/sync_chat_language.py; do not edit.\n' + (
    backend / 'chat/language_detector.ts').read_text(encoding='utf-8').replace(
        '__LANGUAGE_RULES__', json.dumps(rules, ensure_ascii=True))
targets = [workspace / 'serbisure-admin/src/utils/offensiveLanguage.ts',
           workspace / 'front_end_2/SerbiSure-Frontend/src/features/chat/offensiveLanguage.ts']
outputs = {target: source for target in targets}
corpus = (backend / 'chat/language_cases.json').read_text(encoding='utf-8')
outputs[workspace / 'serbisure-admin/tests/fixtures/chat-language-cases.json'] = corpus
outputs[workspace / 'front_end_2/SerbiSure-Frontend/tests/fixtures/chat-language-cases.json'] = corpus
for target, content in outputs.items():
    if '--check' in sys.argv:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Out of date: {target}')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding='utf-8')
print('Chat language checks are synchronized.')
